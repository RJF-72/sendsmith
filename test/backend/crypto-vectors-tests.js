/*
 * CRYPTO GOLDEN VECTORS — the format-compatibility contract.
 *
 * These tests freeze the exact bytes the SendSmith wire/encryption
 * format produces for fixed inputs (see docs/FORMAT.md). Their purpose
 * is longevity: any future runtime, dependency, or implementation swap
 * must reproduce these bytes exactly, so that a client built years from
 * now can still decrypt files shared by today's build — and vice
 * versa. If one of these tests fails after an upgrade, the upgrade
 * changed the format: STOP and treat it as a breaking format change,
 * never "fix" the constant to match new output without a format
 * version bump (docs/FORMAT.md §Versioning).
 *
 * Constants were generated by scripts/generate-crypto-vectors.js,
 * whose manual HKDF/ECE implementations are the same code as the
 * protocol-faithful e2e client (e2e-client.js) — proven byte-compatible
 * with the browser app (WebCrypto) and this server in the e2e suite.
 */
const assert = require('assert');
const crypto = require('crypto');

// Independent HKDF (RFC 5869) built from raw HMAC — deliberately does
// NOT use crypto.hkdfSync, so the two implementations cross-check.
function hkdfManual(ikm, salt, info, len) {
  const saltKey = salt && salt.length ? salt : Buffer.alloc(32);
  const prk = crypto.createHmac('sha256', saltKey).update(ikm).digest();
  let out = Buffer.alloc(0);
  let t = Buffer.alloc(0);
  let i = 0;
  while (out.length < len) {
    i += 1;
    t = crypto
      .createHmac('sha256', prk)
      .update(Buffer.concat([t, Buffer.from(info, 'utf8'), Buffer.from([i])]))
      .digest();
    out = Buffer.concat([out, t]);
  }
  return out.slice(0, len);
}

const SECRET = Buffer.from('00112233445566778899aabbccddeeff', 'hex');
const ECE_SALT = Buffer.from('ffeeddccbbaa99887766554433221100', 'hex');
const PLAINTEXT = Buffer.from(
  'SendSmith golden vector payload — do not change.',
  'utf8'
);

// Frozen expected outputs (Node 22, scripts/generate-crypto-vectors.js)
const EXPECTED = {
  authKey:
    'dc879567b087de9b9cb7f75180b12c0bce72a3e609e7ddd86d7430b5b995828d',
  metaKey: 'e2a4fa1a9b0c40caa07a028aa73727b2',
  nonceB64: 'ASNFZ4mrze/+3LqYdlQyEA==',
  hmacSigB64: 'J/GE0Vkr1QtdOSJ/wyp6mvCUZAWDmjfLhwlxHdosxvI=',
  eceHex:
    'ffeeddccbbaa99887766554433221100000100000036c5cf842156711167d1edbd281c523d7e46177761efa3c16b9205f843fe5bec8a7542fdff04e4c44a25c19659b6f6d75008ed287fd9712c6b68c96e1c60465dd4bc15',
  pbkdf2:
    'a10158af6c01146187105f7190e05b33f4aa3a17b7d4e2cb69d3768b824715a3',
  encMetaB64:
    'pIX1QmgZm9lwZyP+tvl3TRQ14KzsNke5qsljq/kWy02MwZ7LyDePd7uHkC5HLgqoG26sQIuovQ0rRvQNJLtKXnx5nZLjNbQ/9NPBxqLrWnbc2L4='
};

describe('Crypto golden vectors (docs/FORMAT.md)', function() {
  it('HKDF auth key: manual implementation matches the frozen bytes', function() {
    const key = hkdfManual(SECRET, null, 'authentication', 32);
    assert.strictEqual(key.toString('hex'), EXPECTED.authKey);
  });

  it('HKDF auth key: Node builtin hkdfSync matches the frozen bytes', function() {
    const key = crypto.hkdfSync(
      'sha256',
      SECRET,
      Buffer.alloc(32),
      'authentication',
      32
    );
    assert.strictEqual(Buffer.from(key).toString('hex'), EXPECTED.authKey);
  });

  it('HKDF metadata key matches the frozen bytes', function() {
    const key = hkdfManual(SECRET, null, 'metadata', 16);
    assert.strictEqual(key.toString('hex'), EXPECTED.metaKey);
  });

  it('send-v1 HMAC nonce signature matches the frozen bytes', function() {
    // This is the exact computation server/middleware/auth.js verifies:
    // HMAC-SHA256(authKey, nonce) where authKey = HKDF(secret, "authentication").
    const authKey = hkdfManual(SECRET, null, 'authentication', 32);
    const sig = crypto
      .createHmac('sha256', authKey)
      .update(Buffer.from(EXPECTED.nonceB64, 'base64'))
      .digest();
    assert.strictEqual(sig.toString('base64'), EXPECTED.hmacSigB64);
  });

  it('ECE (RFC 8188 aes128gcm) ciphertext matches the frozen bytes', function() {
    const RS = 1024 * 64;
    const key = hkdfManual(SECRET, ECE_SALT, 'Content-Encoding: aes128gcm\0', 16);
    const nonceBase = hkdfManual(
      SECRET,
      ECE_SALT,
      'Content-Encoding: nonce\0',
      16
    ).slice(0, 12);
    const header = Buffer.alloc(21);
    ECE_SALT.copy(header, 0);
    header.writeUInt32BE(RS, 16);
    header.writeUInt8(0, 20);
    // Single record: plaintext + 0x02 delimiter, AES-128-GCM, seq 0.
    const cipher = crypto.createCipheriv('aes-128-gcm', key, Buffer.from(nonceBase));
    const body = Buffer.concat([PLAINTEXT, Buffer.from([2])]);
    const record = Buffer.concat([
      cipher.update(body),
      cipher.final(),
      cipher.getAuthTag()
    ]);
    const out = Buffer.concat([header, record]);
    assert.strictEqual(out.toString('hex'), EXPECTED.eceHex);
  });

  it('ECE frozen ciphertext decrypts back to the plaintext', function() {
    const data = Buffer.from(EXPECTED.eceHex, 'hex');
    const salt = data.slice(0, 16);
    const rs = data.readUInt32BE(16);
    assert.strictEqual(rs, 1024 * 64);
    const key = hkdfManual(SECRET, salt, 'Content-Encoding: aes128gcm\0', 16);
    const nonceBase = hkdfManual(SECRET, salt, 'Content-Encoding: nonce\0', 16).slice(0, 12);
    const rec = data.slice(21);
    const decipher = crypto.createDecipheriv('aes-128-gcm', key, Buffer.from(nonceBase));
    decipher.setAuthTag(rec.slice(rec.length - 16));
    const dec = Buffer.concat([
      decipher.update(rec.slice(0, rec.length - 16)),
      decipher.final()
    ]);
    let i = dec.length - 1;
    while (i >= 0 && dec[i] === 0) i -= 1;
    assert.strictEqual(dec[i], 2); // final-record delimiter
    assert.deepStrictEqual(dec.slice(0, i), PLAINTEXT);
  });

  it('Encrypted metadata blob matches the frozen bytes and decrypts', function() {
    const metaKey = hkdfManual(SECRET, null, 'metadata', 16);
    const cipher = crypto.createCipheriv('aes-128-gcm', metaKey, Buffer.alloc(12));
    const metaJson = JSON.stringify({
      name: 'golden.txt',
      size: 1234,
      type: 'text/plain',
      manifest: {}
    });
    const enc = Buffer.concat([
      cipher.update(metaJson, 'utf8'),
      cipher.final(),
      cipher.getAuthTag()
    ]);
    assert.strictEqual(enc.toString('base64'), EXPECTED.encMetaB64);

    const raw = Buffer.from(EXPECTED.encMetaB64, 'base64');
    const decipher = crypto.createDecipheriv('aes-128-gcm', metaKey, Buffer.alloc(12));
    decipher.setAuthTag(raw.slice(raw.length - 16));
    const dec = Buffer.concat([
      decipher.update(raw.slice(0, raw.length - 16)),
      decipher.final()
    ]);
    assert.strictEqual(JSON.parse(dec.toString()).name, 'golden.txt');
  });

  it('Password path PBKDF2 (100 iterations, salt = share URL) matches', function() {
    // Mirrors app/keychain.js setPassword(): PBKDF2-HMAC-SHA256,
    // 100 iterations, salt = the share URL string.
    const derived = crypto.pbkdf2Sync(
      'correct horse battery staple',
      'https://example.com/download/abc123/#AAAA',
      100,
      32,
      'sha256'
    );
    assert.strictEqual(derived.toString('hex'), EXPECTED.pbkdf2);
  });
});
